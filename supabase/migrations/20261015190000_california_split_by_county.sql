-- CALIFORNIA, SPLIT AT SANTA BARBARA (Bianca's map, 2026-10-15: "NorCal —
-- everything north of Santa Barbara. SoCal — Santa Barbara and everything
-- south of it."). Two reps own California, and until today the line between
-- them was not drawn: a California city was placed only if somebody had typed
-- it into territory_cities by hand, and every other one stayed unplaced
-- (20260904135720_territory_cities).
--
-- The map is read COUNTY BY COUNTY, because a county is a whole a rep can
-- own and a straight latitude line is not: drawn literally through the city
-- of Santa Barbara it would put Lancaster, Palmdale and Barstow — Los Angeles
-- and San Bernardino counties — in Northern California. So:
--   SoCal  = Santa Barbara, Ventura, Los Angeles, Orange, Riverside,
--            San Bernardino, San Diego, Imperial;
--   NorCal = the other fifty, San Luis Obispo (on the map's north side by
--            name) and Kern (north of the line) among them.
--
-- Every California postal town (GeoNames, 1,239 names, none of them in two
-- counties on opposite sides) is then written into territory_cities with its
-- county, so every reader that already places a California city — the ZIP
-- lookup on a new account, the buy-in's ship-to, the sales map — places all
-- of them, with no code of its own. Hand-placed rows keep their territory;
-- the five that existed agree with the line. Moving a county to the other
-- rep later is one update on territory_cities by county.

alter table territory_cities add column county text;

comment on column territory_cities.county is
  'The California county the city sits in; the line between the two California reps is drawn by county (2026-10-15). Null for a hand-placed row outside the postal list.';


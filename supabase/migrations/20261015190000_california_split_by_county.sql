-- Guarded like every prod-data seed: the org and the two territories are
-- production rows, absent from a fresh local reset (the CI suite), where this
-- writes nothing.
insert into territory_cities (org_id, state, city, county, territory_id)
select o.id, 'CA', p.city, p.county, l.territory_id
from ca_places p
join ca_county_line l on l.county = p.county
cross join organizations o
where o.id = '11111111-1111-1111-1111-111111111111'
  and exists (select 1 from territories t where t.id = l.territory_id)
on conflict (org_id, state, city) do update
  set county = excluded.county;

